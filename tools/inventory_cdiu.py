"""Extract Cdiu's real menus/handlers so feature migration is tracked from source."""
from pathlib import Path
import re
import json
import sys

root = Path(__file__).resolve().parents[1]
legacy = Path(sys.argv[1]).resolve() if len(sys.argv)>1 else root / 'CdiuBeatUpEditor-master'
if not legacy.is_dir():
    raise SystemExit('Cdiu source is external. Usage: python tools/inventory_cdiu.py <path-to-Cdiu-source>')
form = (legacy / 'test.frm').read_bytes().decode('cp950', errors='replace')
english = {}
for source in legacy.glob('*.bas'):
    text = source.read_bytes().decode('cp950', errors='replace')
    for name, label in re.findall(r'cmt\.(\w+)\.Caption\s*=\s*"([\x20-\x7e]+)"', text):
        english[name.lower()] = label.strip()
handlers = {m.group(1).lower(): form[:m.start()].count('\n') + 1
            for m in re.finditer(r'(?:Private|Public) Sub (\w+)_Click\(', form)}
menus = []
for m in re.finditer(r'Begin VB.Menu (\w+)\s*\n\s*Caption\s*=\s*"([^"]*)"', form):
    name, caption = m.groups()
    menus.append(dict(id=name, label=english.get(name.lower(), caption),
                      declaration_line=form[:m.start()].count('\n') + 1,
                      handler_line=handlers.get(name.lower())))
status = {
    'openslk': 'Implemented: player File menu, editor Open SLK, Ctrl+O and drag/drop',
    'openmusic': 'Implemented: choose audio in player/editor',
    'saveslkbutton': 'Implemented: native SLK edited-copy export / Save as',
    'checkerror': 'Partial: event/finish/duplicate validation; Cdiu full rule set remains',
    'setting': 'Partial: independent persistent music/effect volume + BPM/native offset controls',
    'setnormalmode': 'Partial: horizontal tick editor, dedicated Space/Finish rows',
    'setseemode': 'Implemented player autoplay; editor follow playback remains',
    'setgamemode': 'Implemented; accepted input feel preserved',
    'cutbutton': 'Implemented selected tick range; lane-specific rectangle selection remains',
    'copybutton': 'Implemented internal clipboard; legacy BBQ clipboard bridge remains',
    'pushupbutton': 'Implemented internal paste',
    'delbutton': 'Implemented selected event deletion',
    'undo': 'Implemented 100-step undo + redo',
    'keyleft': 'Implemented for selected range; select full range for all events',
    'keyright': 'Implemented for selected range; select full range for all events',
    'somekeyleft': 'Implemented selected tick shift -1',
    'somekeyright': 'Implemented selected tick shift +1',
    'allrandomkey': 'Implemented for selected range; select full range for all events',
    'somekeyrandom': 'Implemented direction randomization preserving chord count',
    'autospace16': 'Implemented selected-range generation every 16 ticks',
    'playorstop': 'Implemented explicit Play/Pause/Resume with separate seekable transport',
    'showorhide': 'Implemented editor/player and transport visibility controls',
    'playspace': 'Partial: preview from editor cursor with one-beat lead-in; Space-only looping remains',
}
for menu in menus:
    menu['status'] = status.get(menu['id'].lower(), 'Pending: inspect/port, or identify UI-only group')
out = root / 'docs/CDIU_FEATURE_INVENTORY.json'
out.write_text(json.dumps(menus, ensure_ascii=False, indent=2), encoding='utf-8')
lines = ['# Cdiu source feature inventory', '',
         'Generated by `python tools/inventory_cdiu.py` from the actual VB6 form and',
         'English caption assignments. This is the migration checklist; users do not',
         'need to enumerate individual features. Menu groups are retained for completeness.',
         'A pending entry is not a claim of completion. Hidden network/admin entries',
         'are inventoried but are outside the local player/editor scope.', '',
         '| Cdiu control | Caption | Source handler/declaration | Current status |',
         '| --- | --- | --- | --- |']
for menu in menus:
    label = menu['label'].replace('|', '\\|').replace('\n', ' ')
    line = menu['handler_line'] or menu['declaration_line']
    lines.append(f"| {menu['id']} | {label} | test.frm:{line} | {menu['status']} |")
lines += ['', '## Additional control groups', '',
          'The menu alone does not cover every setting. Transport now supports explicit',
          'Play/Pause/Resume/Restart, seek, inline volume and editor cursor preview.',
          'Still track Space-only looping; BPM segments; autosave/recovery; library paths and song',
          'list metadata; note-speed data; fullscreen/VSync/key labels; timing diagnostics;',
          'background selection; chart validation details; SLK/KBE/DDR/CBE/CBG and ACV;',
          'and settings persistence. Finish presentation is ported from cma4.RenderFinish',
          'and authored from the dedicated Finish row. Original gameplay art, movement,',
          'judgement windows and timestamped input remain the accepted baseline.', '']
(root / 'docs/CDIU_FEATURE_INVENTORY.md').write_text('\n'.join(lines), encoding='utf-8')
print(f'Inventoried {len(menus)} menu entries with source locations')
